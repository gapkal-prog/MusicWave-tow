<?php
/**
 * Persistent application route-state serializer.
 *
 * Emits a pure inert `<script type="application/json" id="mw-route-state">`
 * envelope in `wp_footer` carrying fresh REST configuration, nonces, active
 * release context, and localized frontend script objects so soft navigation can
 * synchronize route configuration through pure `JSON.parse()` without ever
 * re-executing `<head>` or `<body>` inline `<script>` tags.
 *
 * @package ManaCore\MusicWave\Core
 */

declare(strict_types=1);

namespace ManaCore\MusicWave\Core\Support;

use ManaCore\MusicWave\Core\Catalog\ReleasePostType;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

final class FrontendRuntime {
	/**
	 * DOM element ID holding the serialized JSON route state envelope.
	 */
	public const STATE_ELEMENT_ID = 'mw-route-state';

	/**
	 * Known first-party script handles whose localized configs participate in soft navigation.
	 *
	 * @var array<int, string>
	 */
	private const LOCALIZED_HANDLES = array(
		'music-wave-preview-player',
		'music-wave-library',
		'music-wave-download',
		'music-wave-playlists',
		'music-wave-listening',
		'music-wave-queue',
		'music-wave-release-actions',
		'music-wave-request-chat',
		'music-wave-request-form',
		'music-wave-catalog-filters',
		'music-wave-catalog-suggest',
		'music-wave-view-counter',
		'musicwave-slider',
		'musicwave-hero-slider',
		'musicwave-header-search',
		'musicwave-lyrics',
		'musicwave-release-hero',
		'musicwave-rail',
		'musicwave-theme-preference',
	);

	/**
	 * Allowlisted global config object identifiers accepted by the runtime.
	 *
	 * @var array<int, string>
	 */
	public const ALLOWED_GLOBALS = array(
		'mwLibrary',
		'musicWavePreviewPlayer',
		'musicWaveLibrary',
		'musicWaveDownload',
		'musicWavePlaylists',
		'musicWaveListening',
		'musicWaveQueue',
		'musicWaveReleaseActions',
		'musicWaveRequestChat',
		'musicWaveRequestForm',
		'musicWaveCatalogFilters',
		'musicWaveCatalogSuggest',
		'musicWaveViewCounter',
		'musicwaveSlider',
		'musicwaveHeroSlider',
		'musicwaveHeaderSearch',
		'musicwaveLyrics',
		'musicwaveReleaseHero',
		'musicwaveRail',
		'musicwaveTheme',
		'musicwaveThemePreference',
	);

	/**
	 * Register frontend hooks.
	 *
	 * @return void
	 */
	public function register(): void {
		add_action( 'wp_footer', array( $this, 'render_route_state' ), 15 );
	}

	/**
	 * Render the declarative JSON route state payload before footer scripts print.
	 *
	 * @return void
	 */
	public function render_route_state(): void {
		if ( is_admin() ) {
			return;
		}

		$payload = $this->build_payload();
		$encoded = wp_json_encode(
			$payload,
			JSON_HEX_TAG | JSON_HEX_AMP | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
		);
		if ( ! is_string( $encoded ) || '' === $encoded ) {
			return;
		}

		printf(
			'<script type="application/json" id="%s">%s</script>' . "\n",
			esc_attr( self::STATE_ELEMENT_ID ),
			$encoded // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON_HEX_TAG | JSON_HEX_AMP encoded for <script type="application/json">.
		);
	}

	/**
	 * Build the structured route state array for the current request.
	 *
	 * @return array<string, mixed>
	 */
	public function build_payload(): array {
		$release_id = ( function_exists( 'is_singular' ) && is_singular( ReleasePostType::KEY ) && function_exists( 'get_queried_object_id' ) )
			? (int) get_queried_object_id()
			: 0;

		return array(
			'restUrl'   => function_exists( 'rest_url' ) ? esc_url_raw( rest_url() ) : '',
			'restNonce' => function_exists( 'wp_create_nonce' ) ? wp_create_nonce( 'wp_rest' ) : '',
			'loggedIn'  => function_exists( 'get_current_user_id' ) && get_current_user_id() > 0,
			'releaseId' => $release_id,
			'configs'   => $this->collect_localized_configs(),
		);
	}

	/**
	 * Extract pure JSON objects registered via `wp_localize_script` on known handles.
	 *
	 * @return array<string, array<string, mixed>>
	 */
	public function collect_localized_configs(): array {
		if ( ! function_exists( 'wp_scripts' ) ) {
			return array();
		}

		$scripts = wp_scripts();
		if ( ! is_object( $scripts ) || ! method_exists( $scripts, 'get_data' ) ) {
			return array();
		}

		$configs = array();
		foreach ( self::LOCALIZED_HANDLES as $handle ) {
			$raw = $scripts->get_data( $handle, 'data' );
			if ( ! is_string( $raw ) || '' === trim( $raw ) ) {
				continue;
			}
			foreach ( self::parse_localized_assignments( $raw ) as $key => $value ) {
				$configs[ $key ] = $value;
			}
		}

		return $configs;
	}

	/**
	 * Safely parse `var <AllowedIdentifier> = <JSON>;` blocks generated by `WP_Scripts::localize`
	 * using string-aware balanced brace matching so embedded `};` substrings inside JSON strings
	 * never truncate the serialized object.
	 *
	 * @param string $script_text Raw script data buffer.
	 * @return array<string, array<string, mixed>>
	 */
	public static function parse_localized_assignments( string $script_text ): array {
		$parsed    = array();
		$allowlist = array_flip( self::ALLOWED_GLOBALS );
		$length    = strlen( $script_text );

		if ( ! preg_match_all( '/\bvar\s+([A-Za-z0-9_]+)\s*=\s*\{/', $script_text, $matches, PREG_OFFSET_CAPTURE ) ) {
			return $parsed;
		}

		foreach ( $matches[1] as $idx => $name_capture ) {
			$name = (string) $name_capture[0];
			if ( ! isset( $allowlist[ $name ] ) ) {
				continue;
			}

			$full_match = $matches[0][ $idx ];
			$brace_pos  = (int) $full_match[1] + strlen( (string) $full_match[0] ) - 1;
			$json_text  = self::extract_balanced_braces( $script_text, $brace_pos, $length );
			if ( '' === $json_text ) {
				continue;
			}

			$decoded = json_decode( $json_text, true );
			if ( is_array( $decoded ) ) {
				$parsed[ $name ] = $decoded;
			}
		}

		return $parsed;
	}

	/**
	 * Extract a balanced `{ ... }` substring respecting JSON string escapes.
	 */
	private static function extract_balanced_braces( string $source, int $start, int $length ): string {
		if ( $start < 0 || $start >= $length || '{' !== $source[ $start ] ) {
			return '';
		}

		$depth     = 0;
		$in_string = false;
		$escaped   = false;

		for ( $i = $start; $i < $length; ++$i ) {
			$char = $source[ $i ];

			if ( $in_string ) {
				if ( $escaped ) {
					$escaped = false;
				} elseif ( '\\' === $char ) {
					$escaped = true;
				} elseif ( '"' === $char ) {
					$in_string = false;
				}
				continue;
			}

			if ( '"' === $char ) {
				$in_string = true;
			} elseif ( '{' === $char ) {
				++$depth;
			} elseif ( '}' === $char ) {
				--$depth;
				if ( 0 === $depth ) {
					return substr( $source, $start, $i - $start + 1 );
				}
			}
		}

		return '';
	}
}
